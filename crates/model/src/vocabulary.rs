pub fn biome_subtype_present(biome: usize, choice: usize) -> bool {
    let mask: u64 = match biome {
        0 => 0x5fc7047,
        1 => 0x1cfc0045,
        2 => 0xe9a0045,
        3 => 0x1ca90005,
        4 => 0x1cb90007,
        5 => 0x4f91047,
        6 => 0x190001,
        7 => 0x1ffc,
        8 => 0x7e000,
        9 => 0x7e000,
        10 => 0x7e000,
        12 => 0x10000001,
        13 => 0x10000001,
        14 => 0x4780001,
        15 => 0x1,
        16 => 0x7e000,
        _ => 0,
    };
    choice < 31 && mask & (1 << choice) != 0
}

